-- Analytic functions on SQl ----

-- ------------------------Row Number() -----------------------------

SELECT
    employee_id,
    first_name,
    salary,

    ROW_NUMBER() OVER (
        ORDER BY salary DESC
    ) AS row_num

FROM hr.employees;

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, ROW_NUMBER() OVER(ORDER BY SALARY ASC) AS ROW_NUM FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, ROW_NUMBER() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS ROW_NUM FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, HIRE_DATE, ROW_NUMBER() OVER( ORDER BY HIRE_DATE ASC) AS JOINING_ORDER FROM HR.EMPLOYEES;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, HIRE_DATE, ROW_NUMBER() OVER(PARTITION BY DEPARTMENT_ID ORDER BY HIRE_DATE DESC) AS rn FROM HR.EMPLOYEES) WHERE rn = 1;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, ROW_NUMBER() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS RN FROM HR.EMPLOYEES) WHERE RN <= 3 ;


-- ---------------------------------------RANK()---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, RANK() OVER(ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, RANK() OVER(ORDER BY SALARY ASC) AS SALARY_RANK FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS DEPARTMENT_RANK FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, HIRE_DATE, RANK() OVER( ORDER BY HIRE_DATE ASC) AS JOINING_RANK FROM HR.EMPLOYEES;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES) WHERE SALARY_RANK = 1;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES) WHERE SALARY_RANK <= 3 ;

-- ----------------DENSE RANK()-----------------------------------------------------

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, DENSE_RANK() OVER(ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, DENSE_RANK() OVER(ORDER BY SALARY ASC) AS SALARY_RANK FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, DENSE_RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS DEPARTMENT_RANK FROM HR.EMPLOYEES;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, DENSE_RANK() OVER(ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES) WHERE SALARY_RANK = 2;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, DENSE_RANK() OVER(ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES) WHERE SALARY_RANK = 3;

SELECT * FROM (SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY, DENSE_RANK() OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS SALARY_RANK FROM HR.EMPLOYEES) WHERE SALARY_RANK = 2;

-- -----------------FIRST_VALUE()-------------------------------

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, FIRST_VALUE(SALARY) OVER(ORDER BY SALARY DESC) AS HIGHEST_SALARY FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, FIRST_VALUE(SALARY) OVER(ORDER BY SALARY ASC) AS LOWEST_SALARY FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY,FIRST_VALUE(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS DEPARTMENT_HIGHEST FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, SALARY,FIRST_VALUE(FIRST_NAME) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS HIGHEST_PAID_EMPLOYEE FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, HIRE_DATE,FIRST_VALUE(HIRE_DATE) OVER(PARTITION BY DEPARTMENT_ID ORDER BY HIRE_DATE ASC) AS EARLIEST_HIRE_DATE FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, DEPARTMENT_ID, HIRE_DATE,FIRST_VALUE(FIRST_NAME) OVER(PARTITION BY DEPARTMENT_ID ORDER BY HIRE_DATE ASC) AS FIRST_JOINED_EMPLOYEE FROM HR.EMPLOYEES;

-- -----------LAST_VALUE()------------------------------------------------------------------------------------------------------------------------------------------------------------------

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, LAST_VALUE(SALARY) OVER(ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS LOWEST_SALARY FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME, SALARY, LAST_VALUE(SALARY) OVER(ORDER BY SALARY ASC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS HIGHEST_SALARY FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME,DEPARTMENT_ID, SALARY, LAST_VALUE(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS DEPARTMENT_LOWEST_SALARY FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME,DEPARTMENT_ID, SALARY, LAST_VALUE(FIRST_NAME) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS LOWEST_PAID_EMPLOYEE FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME,DEPARTMENT_ID, HIRE_DATE, LAST_VALUE(HIRE_DATE) OVER(PARTITION BY DEPARTMENT_ID ORDER BY HIRE_DATE ASC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS LATEST_JOINED_EMPLOYEE FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, FIRST_NAME,DEPARTMENT_ID, SALARY,FIRST_VALUE(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS HIGHEST_DEPARTMENT_SALARY ,LAST_VALUE(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING  AND UNBOUNDED FOLLOWING ) AS LOWEST_DEPARTMENT_SALARY FROM HR.EMPLOYEES;
